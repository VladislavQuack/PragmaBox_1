// Демо-данные: клиенты из «Загрузить демо-данные». Их можно убрать одной кнопкой,
// не трогая настоящих клиентов тренера.

// Заметка, по которой демо-клиента видно в карточке и по которой его потом находим
export const DEMO_NOTE = "Демо-клиент для знакомства с приложением";

// Демо-клиенты из старых версий (до заметки) — узнаём по имени и вымышленному номеру
const LEGACY_DEMO: [string, string][] = [
  ["Мария", "+7 900 111-22-33"],
  ["Михаил", "+7 900 222-33-44"],
  ["Владимир", "+7 900 333-44-55"],
  ["Ольга", "+7 900 444-55-66"],
];

export function isDemoClient(c: { name: string; phone: string | null; note: string | null }): boolean {
  if (c.note === DEMO_NOTE) return true;
  return LEGACY_DEMO.some(([name, phone]) => c.name === name && c.phone === phone);
}
